#!/usr/bin/env node
// Writes src/features/courses/content/catalog/courses.generated.ts: the registered courses, in syllabus order.
// A course is registered only once its file passes its checks (writers work in catalog/courses/ while a file is half written).
// Usage: node scripts/content/build-catalog-index.mjs [course-id ...]   (ids are added to catalog/registered.json)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const catalog = join(root, 'src/features/courses/content/catalog');
const syllabus = ['syllabus-ai-1.ts', 'syllabus-ai-2.ts', 'syllabus-foundations.ts', 'syllabus-dsa.ts', 'syllabus-oop.ts', 'syllabus-soft-skills.ts', 'syllabus-international-clients.ts', 'syllabus-genai.ts', 'syllabus-productivity.ts', 'syllabus-ai-fundamentals.ts', 'syllabus-architecture.ts', 'syllabus-llm.ts', 'syllabus-ai-automation.ts', 'syllabus-agents.ts'].flatMap((file) => [...readFileSync(join(catalog, file), 'utf8').matchAll(/^    id: '([a-z0-9-]+)',$/gm)].map((match) => match[1]));
const files = new Set(readdirSync(join(catalog, 'courses')).filter((file) => file.endsWith('.ts') && !file.endsWith('.test.ts')).map((file) => file.slice(0, -3)));
const registeredFile = join(catalog, 'registered.json');
const registered = new Set([...(existsSync(registeredFile) ? JSON.parse(readFileSync(registeredFile, 'utf8')) : []), ...process.argv.slice(2)]);
for (const id of registered) if (!files.has(id)) throw new Error(`${id} is registered but has no file in catalog/courses/`);
const present = syllabus.filter((id) => registered.has(id));
writeFileSync(registeredFile, JSON.stringify(present, null, 2) + '\n');
const camel = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()) + 'Course';
const lines = [
  '// Generated by scripts/content/build-catalog-index.mjs: do not edit by hand.',
  "import type { Course } from '../types';",
  ...present.map((id) => `import { ${camel(id)} } from './courses/${id}';`),
  '',
  `export const GENERATED_CATALOG_COURSES: readonly Course[] = [${present.map(camel).join(', ')}];`,
  '',
];
writeFileSync(join(catalog, 'courses.generated.ts'), lines.join('\n'));
console.log(`${present.length} of ${syllabus.length} courses registered.`);
