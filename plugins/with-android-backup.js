/**
 * Android's system backup (Auto Backup, Google Account backup, device-to-device transfer) for Talino,
 * kept deliberately small. Only the folder `files/backups/` goes into the backup: it holds Talino's own
 * versioned snapshot (`*.talino-backup`, written by features/backup after every change). The live SQLite
 * database and the key-value store are NOT backed up, so Android can never restore a raw database file
 * over a newer app: after a reinstall or a new phone the app finds the restored snapshot and merges it
 * in, with the same rules as every other restore (newer progress is never overwritten).
 *
 * Auto Backup is system-managed: Android decides when it runs and whether the user has it on
 * (Settings → Google → Backup). Talino can't ask the system whether a backup reached Google, and the app says so.
 * Rules are written for both mechanisms: `fullBackupContent` (Android 6-11) and `dataExtractionRules` (Android 12+, cloud
 * backup and device-to-device transfer).
 */
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const BACKUP_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Talino: back up only the snapshot folder (files/backups). Generated by plugins/with-android-backup.js. -->
<full-backup-content>
  <include domain="file" path="backups/" />
</full-backup-content>
`;

const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Talino: cloud backup and device-to-device transfer carry only the snapshot folder (files/backups). Generated by plugins/with-android-backup.js. -->
<data-extraction-rules>
  <cloud-backup>
    <include domain="file" path="backups/" />
  </cloud-backup>
  <device-transfer>
    <include domain="file" path="backups/" />
  </device-transfer>
</data-extraction-rules>
`;

module.exports = function withAndroidBackup(config) {
  config = withAndroidManifest(config, (mod) => {
    const application = mod.modResults.manifest.application?.[0];
    if (application) {
      application.$['android:allowBackup'] = 'true';
      application.$['android:fullBackupContent'] = '@xml/talino_backup_rules';
      application.$['android:dataExtractionRules'] = '@xml/talino_data_extraction_rules';
    }
    return mod;
  });
  return withDangerousMod(config, [
    'android',
    async (mod) => {
      const folder = path.join(mod.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(folder, { recursive: true });
      fs.writeFileSync(path.join(folder, 'talino_backup_rules.xml'), BACKUP_RULES);
      fs.writeFileSync(path.join(folder, 'talino_data_extraction_rules.xml'), DATA_EXTRACTION_RULES);
      return mod;
    },
  ]);
};

module.exports.BACKUP_RULES = BACKUP_RULES;
module.exports.DATA_EXTRACTION_RULES = DATA_EXTRACTION_RULES;
