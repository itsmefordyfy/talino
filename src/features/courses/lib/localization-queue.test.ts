import { describe, expect, test } from '@jest/globals';
import fs from 'node:fs';
import path from 'node:path';

import { COURSES } from '../content';
import { FIL_COURSES } from '../content/fil';
import type { Course } from '../content/types';
import { translatableStrings } from './localization-parity';
import { localizationReport, type CourseReport } from './localization-report';
import { TAGALOG_ENABLED } from '@/lib/language';

/**
 * The honest map of what is Tagalog-ready. A course is ready only when `content/fil` holds a complete translation (the parity
 * test in `localization.test.ts` proves it keeps every lesson, quiz, activity and project). Run `npm run i18n:queue` to rewrite
 * `docs/i18n/TRANSLATION_QUEUE.md` from the live catalog: what is done, what is next, and how big each course is.
 */
const ORDER: Record<Course['kind'], number> = { starter: 0, career: 1, mini: 2, path: 3, standard: 4 };

function words(course: Course): number {
  return translatableStrings(course).reduce((total, entry) => total + entry.text.split(/\s+/).length, 0);
}

describe('translation queue', () => {
  test('a course counts as Tagalog-ready only when it has a complete translation registered', () => {
    for (const course of COURSES) {
      const translated = FIL_COURSES[course.id];
      if (!translated) continue;
      expect(translated.lessons.map((lesson) => lesson.id)).toEqual(course.lessons.map((lesson) => lesson.id));
      expect(translated.projects.map((project) => project.id)).toEqual(course.projects.map((project) => project.id));
    }
    expect(Object.keys(FIL_COURSES).every((id) => COURSES.some((course) => course.id === id))).toBe(true);
  });

  test('writes the queue document when asked (npm run i18n:queue)', () => {
    if (process.env.WRITE_QUEUE !== '1') return;
    const rows = [...COURSES].sort((a, b) => ORDER[a.kind] - ORDER[b.kind]);
    const ready = rows.filter((course) => FIL_COURSES[course.id]);
    const waiting = rows.filter((course) => !FIL_COURSES[course.id]);
    const totalWords = waiting.reduce((sum, course) => sum + words(course), 0);
    const line = (course: Course) => `| ${course.id} | ${course.kind} | ${course.lessons.length} | ${course.projects.length} | ${words(course).toLocaleString('en-US')} |`;
    const header = '| Course | Kind | Lessons | Projects | Words to translate |\n|---|---|---|---|---|';
    const text = `# Tagalog translation queue

Generated by \`npm run i18n:queue\` (${new Date().toISOString().slice(0, 10)}). Do not edit by hand. A course is **Tagalog-ready** only when
\`content/fil/index.ts\` registers a complete translation that passes \`localization.test.ts\`; every other course stays English and is
labelled "English lang muna" in Tagalog mode. The voice and glossary are in \`tagalog-style-guide.md\`.

**Ready:** ${ready.length} of ${rows.length} courses. **Waiting:** ${waiting.length} courses, about ${totalWords.toLocaleString('en-US')} words of prose.

## Ready

${header}
${ready.map(line).join('\n') || '| none | | | | |'}

## Waiting, in the order to translate them

Starter first, then the career courses, mini-courses, the AI-assisted development path, then the wider catalog.

${header}
${waiting.map(line).join('\n')}
`;
    fs.writeFileSync(path.join(__dirname, '../../../../docs/i18n/TRANSLATION_QUEUE.md'), text);
  });

  test('writes the localization report when asked (npm run i18n:queue)', () => {
    if (process.env.WRITE_QUEUE !== '1') return;
    const report = localizationReport(COURSES, FIL_COURSES, 'fil');
    const t = report.totals;
    const n = (value: number) => value.toLocaleString('en-US');
    const label: Record<CourseReport['status'], string> = { full: 'Tagalog', partial: 'Partly Tagalog', english: 'English only' };
    const sorted = [...report.courses].sort((a, b) => ORDER[a.kind] - ORDER[b.kind]);
    const row = (course: CourseReport) => {
      const done = course.lessons.filter((lesson) => lesson.translated).length;
      const narration = course.lessons.filter((lesson) => lesson.englishNarration > 0).length;
      return `| ${course.id} | ${course.kind} | ${label[course.status]} | ${done} / ${course.lessons.length} | ${course.lessons.length - narration} / ${course.lessons.length} | ${course.lessons.reduce((sum, lesson) => sum + lesson.textProblems, 0) + course.courseTextProblems} | ${n(course.words)} |`;
    };
    const partial = sorted.filter((course) => course.status === 'partial');
    const missing = sorted.filter((course) => course.status === 'english');
    const text = `# Tagalog localization report

Generated by \`npm run i18n:queue\` (${new Date().toISOString().slice(0, 10)}) from the live catalog (\`lib/localization-report.ts\`). Do not edit by
hand. What "localized" means here is checked, not assumed: a course is **Tagalog** only when \`content/fil/index.ts\` registers a complete
translation (the parity test proves every lesson, quiz, activity and project is there with the same code and answers), no text field of it
reads as English or as the stiff Filipino the style guide bans, and **what Listen says for each lesson** (the exact sentences sent to Gemini
TTS or the phone's voice, \`lessonSegments(lesson, 'fil')\`) has no English sentence. Talino has no modules: a course is a list of lessons
(by day) and projects; categories and learning paths group courses, and their names and descriptions are in Tagalog
(\`catalog/catalog-text.ts\`, checked by \`catalog-text.test.ts\`).
${TAGALOG_ENABLED ? '' : `
**Tagalog is switched off in the app** (\`TAGALOG_ENABLED = false\` in \`src/lib/language.ts\`; owner, 2026-11-15: focus on English for now).
Learners see English everywhere and no language picker; a saved Tagalog choice is kept and comes back when the switch is turned on. This
report is what a learner would get in Tagalog today if it were on.
`}
## Summary

| | |
|---|---|
| Published courses | ${t.courses} |
| Lessons | ${n(t.lessons)} (plus ${t.projects} projects, ${n(t.quizQuestions)} quiz questions) |
| Fully in Tagalog | ${t.full} courses |
| Partly in Tagalog | ${t.partial} courses |
| English only ("English lang muna" in Tagalog mode) | ${t.english} courses |
| Lessons with no Tagalog version | ${n(t.lessonsMissing)} of ${n(t.lessons)} |
| Lessons whose narration in Tagalog mode still has English | ${n(t.lessonsWithEnglishNarration)} of ${n(t.lessons)} (an untranslated lesson is read in English, as it is shown) |
| English prose still to translate | about ${n(t.wordsWaiting)} of ${n(t.words)} words |

## Every course

"Narration in Tagalog" counts lessons whose every spoken sentence is Tagalog/Taglish. "Text flags" counts text fields that read as English
or too formal (\`textProblems\`; Taglish with English tech terms passes).

| Course | Kind | Status | Lessons in Tagalog | Narration in Tagalog | Text flags | Words |
|---|---|---|---|---|---|---|
${sorted.map(row).join('\n')}
${partial.length ? `
## Partly translated: what still reads as English

${partial.map((course) => `- **${course.id}**: ${course.lessons.filter((lesson) => lesson.textProblems > 0 || lesson.englishNarration > 0).map((lesson) => `${lesson.id} (${lesson.textProblems} text, ${lesson.englishNarration} spoken)`).join(', ') || 'course page or projects'}`).join('\n')}
` : ''}
## Lessons still missing a Tagalog translation

${missing.length ? missing.map((course) => `- **${course.id}** (${course.lessons.length}): ${course.lessons.map((lesson) => lesson.id).join(', ')}`).join('\n') : 'None.'}
`;
    fs.writeFileSync(path.join(__dirname, '../../../../docs/i18n/LOCALIZATION_REPORT.md'), text);
  });
});
