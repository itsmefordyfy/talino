/**
 * Checks one module of Software Architecture with AI while it is written (its lessons live in `courses/software-architecture-ai/module-NN.ts`):
 * `CHECK_ARCH_MODULE=3 npx jest --no-watchman src/features/courses/content/catalog/architecture-module`. The module's lessons are placed at their real days in a
 * course whose other lessons are stubs, and only the problems that name this module's lessons are reported, plus the lesson shape and the AI practice.
 * The whole-course checks run in `check-one` (`CHECK_COURSE=software-architecture-ai`) once every module exists.
 */
const COURSE = 'software-architecture-ai';
const HEADINGS = { situation: 'A real situation', concept: 'How it works', action: 'AI in Action', tryit: 'Try it with AI', next: 'Next steps' };

export function shapeProblems(lesson: Lesson): string[] {
  const problems: string[] = [];
  const at = (text: string) => lesson.body.findIndex((block) => block.type === 'heading' && block.text.trim() === text);
  if (lesson.body[0]?.type !== 'paragraph') problems.push('must open with a paragraph');
  const index = { situation: at(HEADINGS.situation), concept: at(HEADINGS.concept), action: at(HEADINGS.action), tryit: at(HEADINGS.tryit), next: at(HEADINGS.next) };
  for (const key of Object.keys(HEADINGS) as (keyof typeof HEADINGS)[]) if (index[key] < 0) problems.push(`missing the heading "${HEADINGS[key]}"`);
  const order = [index.situation, index.concept, index.action, index.tryit, index.next];
  if (order.every((value) => value >= 0) && order.some((value, position) => position > 0 && value < order[position - 1])) problems.push('the headings must run: A real situation, How it works, AI in Action, Try it with AI, Next steps');
  const demos = lesson.body.flatMap((block, position) => (block.type === 'demo' ? [position] : []));
  if (demos.length === 0) problems.push('"AI in Action" needs a demo block');
  else if (index.action >= 0 && index.tryit >= 0 && !demos.some((position) => position > index.action && position < index.tryit)) problems.push('the demo block belongs between "AI in Action" and "Try it with AI"');
  for (const block of lesson.body) if (block.type === 'demo' && /real (model|output|response)|actual (model|output)|generated by (chatgpt|gemini|claude)|recorded/i.test(`${block.title} ${block.notice}`)) problems.push('a demo is an illustration: do not call it a real model output');
  if (index.tryit >= 0 && !lesson.body.slice(index.tryit, index.next >= 0 ? index.next : undefined).some((block) => block.type === 'prompt')) problems.push('"Try it with AI" needs a prompt block the learner can copy into their own assistant');
  if (index.next >= 0 && !lesson.body.slice(index.next).some((block) => block.type === 'list')) problems.push('"Next steps" needs a list of recommended next steps');
  const takeaways = lesson.body.findIndex((block) => block.type === 'takeaways');
  if (takeaways < 0) problems.push('no takeaways');
  else if (index.next >= 0 && takeaways < index.next) problems.push('the takeaways come last, after "Next steps"');
  if (!lesson.body.some((block) => block.type === 'diagram' || block.type === 'visual')) problems.push('needs a diagram or an interactive visual');
  const kinds = new Set(lesson.body.flatMap((block) => (block.type === 'activity' ? [block.activity.kind] : [])));
  if (kinds.size < 2) problems.push(`needs at least two activities of different kinds, has ${kinds.size} kind(s)`);
  if (!lesson.body.some((block) => block.audience && block.audience.max && !block.audience.min)) problems.push('needs a plain-language block for newcomers (audience { max: "beginner" })');
  if (!lesson.body.some((block) => block.audience && block.audience.min && !block.audience.max)) problems.push('needs a depth block for experienced learners (audience { min: "advanced" })');
  if ((lesson.taskExtra ?? []).length === 0) problems.push('needs taskExtra for at least one level (a harder challenge for professionals)');
  return problems;
}

/** Every `prompt-lab` names a lab that exists; the module's labs (`arch-NN-…`) are each used exactly once. `minLabs` is the module's minimum. */
export function practiceProblems(lessons: Lesson[], moduleNumber: number, minLabs = 0): string[] {
  const problems: string[] = [];
  const used: string[] = [];
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { findPracticeItem, PRACTICE_ITEMS } = require('../../../practice/catalog') as typeof import('../../../practice/catalog');
  for (const lesson of lessons) {
    for (const block of lesson.body) {
      if (block.type !== 'activity' || block.activity.kind !== 'prompt-lab') continue;
      const item = findPracticeItem(block.activity.labId);
      used.push(block.activity.labId);
      if (!item) problems.push(`${lesson.id}: ${block.activity.id} names ${block.activity.labId}, which is not in practice/labs`);
      else if (item.kind !== 'lab') problems.push(`${lesson.id}: ${block.activity.id} names ${block.activity.labId}, which is a ${item.kind}`);
    }
  }
  const prefix = `arch-${String(moduleNumber).padStart(2, '0')}-`;
  const mine = PRACTICE_ITEMS.filter((item) => item.id.startsWith(prefix));
  for (const item of mine) {
    const count = used.filter((id) => id === item.id).length;
    if (count !== 1) problems.push(`${item.id} is used by ${count} activities (exactly one expected)`);
  }
  if (mine.length < minLabs) problems.push(`the module needs at least ${minLabs} prompt lab(s) with ids starting ${prefix}, has ${mine.length}`);
  return problems;
}

const number = process.env.CHECK_ARCH_MODULE;
const run = number ? describe : describe.skip;

run(`${COURSE} module ${number ?? '(none named)'}`, () => {
  test('follows every lesson rule and has the lesson parts', () => {
    const syllabus = getSyllabus(COURSE)!;
    const index = Number(number) - 1;
    const first = (syllabus.modules ?? []).slice(0, index).reduce((sum, module) => sum + module.topics.length, 0);
    const count = syllabus.modules?.[index]?.topics.length ?? 0;
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const loaded = require(`./courses/${COURSE}/module-${String(number).padStart(2, '0')}`) as { lessons: Lesson[]; project: Project | null };
    expect(loaded.lessons).toHaveLength(count);
    // Lesson ids are `generative-ai-applications-NN` with NN the day across the whole course.
    expect(loaded.lessons.map((lesson) => lesson.id)).toEqual(loaded.lessons.map((_, i) => `${COURSE}-${String(first + i + 1).padStart(2, '0')}`));
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const skills = (require(`./courses/${COURSE}/skills`) as { SKILLS: Course['skills'] }).SKILLS;
    const stub = (position: number): Lesson => ({
      id: `${COURSE}-${String(position + 1).padStart(2, '0')}`,
      day: position + 1,
      title: syllabus.topics[position]!,
      summary: 'stub',
      minutes: 10,
      skills: [],
      body: [],
      quiz: [],
      task: { title: 'stub', steps: [], minutes: 5 },
    });
    const lessons = syllabus.topics.map((_, position) => (position >= first && position < first + count ? loaded.lessons[position - first]! : stub(position)));
    const ordinal = loaded.project ? Number(/-p(\d+)$/.exec(loaded.project.id)?.[1] ?? 0) : 0;
    const projects: Project[] = loaded.project
      ? Array.from({ length: ordinal }, (_, position) => (position === ordinal - 1 ? loaded.project! : { id: `${COURSE}-p${position + 1}`, title: 'stub', summary: 'stub', outcome: 'stub', unlockAfterDay: 1, steps: [], submission: { kind: 'text', label: 'x', placeholder: 'x', hint: 'x' }, rubric: [] }))
      : [];
    const course: Course = {
      id: COURSE,
      kind: 'standard',
      title: syllabus.title,
      level: 'intermediate',
      tagline: 'A tagline that is long enough to pass',
      description: 'A description long enough to pass the length check of the course rules for the course page.',
      finishLine: ['one', 'two'],
      objectives: ['Explain what software architecture is', 'Compare two solutions', 'Choose a tool'],
      audiences: ['experienced-dev'],
      skills,
      lessons,
      projects,
      icon: 'code',
      updated: '2026-11-16',
    };
    const mine = new Set([...loaded.lessons.map((lesson) => lesson.id), ...(loaded.project ? [loaded.project.id] : [])]);
    const problems = standardCourseProblems(course).filter((problem) => [...mine].some((id) => problem.includes(id)) || /quiz answers|longest choice/.test(problem));
    const shape = loaded.lessons.flatMap((lesson) => shapeProblems(lesson).map((problem) => `${lesson.id}: ${problem}`));
    expect([...problems, ...shape, ...practiceProblems(loaded.lessons, Number(number), Number(process.env.CHECK_ARCH_MIN_LABS ?? 0))]).toEqual([]);
  });
});
