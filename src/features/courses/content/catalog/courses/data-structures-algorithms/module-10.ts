/** Joins lines of code or of a Mermaid diagram, so every block reads as it will be shown. */
const rows = (...lines: string[]) => lines.join('\n');

/** A perfect binary tree of nested plain objects (height h has 2^(h+1) - 1 nodes), for tests that pass a whole tree as an argument. */
const perfect = (height: number): unknown => (height < 0 ? null : { value: 1, left: perfect(height - 1), right: perfect(height - 1) });

/** A tree that only ever goes right, `count` nodes tall. */
const chain = (count: number): unknown => (count === 0 ? null : { value: count, left: null, right: chain(count - 1) });

/** A file and a folder of the folder-tree tests. */
const file = (name: string, size: number) => ({ name, size });
const folder = (name: string, ...children: unknown[]) => ({ name, children });
/** A folder nested `levels` deep with a 5 KB file at the bottom. */
const deepFolder = (levels: number): unknown => (levels === 0 ? file('bottom.txt', 5) : folder(`level-${levels}`, deepFolder(levels - 1)));

/** One node of a test tree, as a plain object. */
const node = (value: number, left: unknown = null, right: unknown = null) => ({ value, left, right });

