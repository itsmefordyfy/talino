import { describe, expect, test } from '@jest/globals';

import { standardCourseProblems } from '../../lib/standard-rules';
import { EXPERIENCE_LEVELS, inAudience } from '../levels';
import type { Course, Lesson, LessonBlock, Project } from '../types';
import { getSyllabus } from './syllabus';

/**
 * Checks one module of Building AI Agents while it is written (its lessons live in `courses/building-ai-agents/module-NN.ts`):
 * `CHECK_AGENTS_MODULE=3 npx jest --no-watchman src/features/courses/content/catalog/agents-module`. The module's lessons are placed at their real days in a course whose other
 * lessons are stubs, and only the problems that name this module's lessons are reported, plus the lesson shape. The whole-course checks run in `building-ai-agents.course.test.ts`.
 *
 * Modules 1 to 11 teach: an opening paragraph, "A real situation", "How it works" (with a diagram, a visual or a table), then "Build it" (code the learner can run, followed by "Run it and
 * check": the expected output, what to do when it goes wrong, and the security point) or, in a concept lesson, "Try it yourself"; then "Next steps" and takeaways. Module 12 is the
 * review, the six-part 30-question assessment and the capstone guide, which have their own shape.
 */
const COURSE = 'building-ai-agents';
const HEADINGS = { situation: 'A real situation', concept: 'How it works', build: 'Build it', check: 'Run it and check', tryit: 'Try it yourself', next: 'Next steps' };
/** The assessment lessons of module 12 (days 103 to 108): five questions each, 30 in all. */
export const ASSESSMENT_DAYS = [103, 104, 105, 106, 107, 108] as const;
export const REVIEW_DAY = 102;
export const CAPSTONE_DAY = 109;
const RUNNABLE = /^(python|py|typescript|ts|javascript|js|bash|sh|shell|sql)$/i;
const CODE_ACTIVITIES = new Set(['code-challenge', 'fix-bug', 'predict-output']);

const headingAt = (body: LessonBlock[], text: string) => body.findIndex((block) => block.type === 'heading' && block.text.trim() === text);

export function shapeProblems(lesson: Lesson, day: number): string[] {
  const problems: string[] = [];
  const body = lesson.body;
  const kinds = new Set(body.flatMap((block) => (block.type === 'activity' ? [block.activity.kind] : [])));
  if (body[0]?.type !== 'paragraph') problems.push('must open with a paragraph');
  const takeaways = body.findIndex((block) => block.type === 'takeaways');
  if (takeaways < 0) problems.push('no takeaways');
  else if (takeaways !== body.length - 1 && body.slice(takeaways + 1).some((block) => block.type !== 'activity')) problems.push('the takeaways come last (activities may follow)');
  for (const block of body) if (block.type === 'demo' && /real (model|output|response)|actual (model|output)|generated by (chatgpt|gemini|claude)|recorded/i.test(`${block.title} ${block.notice}`)) problems.push('a demo is an illustration: do not call it a real model output');

  if ((ASSESSMENT_DAYS as readonly number[]).includes(day)) {
    for (const level of EXPERIENCE_LEVELS) {
      const asked = lesson.quiz.filter((question) => inAudience(question.audience, level)).length;
      if (asked !== 5) problems.push(`assessment part: ${level} is asked ${asked} questions, must be exactly 5 (30 over the six parts)`);
    }
    for (const question of lesson.quiz) if (question.choices.length !== 4) problems.push(`${question.id}: assessment questions have exactly four choices`);
    if (lesson.quiz.filter((question) => !question.audience).length !== 4) problems.push('assessment part: exactly 4 shared questions (the other questions are level-band ones)');
    if (!lesson.quiz.some((question) => /scenario|a team|an agent|your agent|you are|you have|a developer|builds|building|runs|returns|log shows|trace/i.test(question.prompt))) problems.push('assessment part: include practical scenario-based questions');
    return problems;
  }
  if (day === REVIEW_DAY || day === CAPSTONE_DAY) {
    if (!body.some((block) => block.type === 'diagram' || block.type === 'visual' || block.type === 'table')) problems.push('needs a diagram, a visual or a table');
    if (kinds.size < 1) problems.push('needs at least one activity');
    return problems;
  }

  const at = (text: string) => headingAt(body, text);
  const index = { situation: at(HEADINGS.situation), concept: at(HEADINGS.concept), build: at(HEADINGS.build), check: at(HEADINGS.check), tryit: at(HEADINGS.tryit), next: at(HEADINGS.next) };
  if (index.situation < 0) problems.push(`missing the heading "${HEADINGS.situation}"`);
  if (index.concept < 0) problems.push(`missing the heading "${HEADINGS.concept}"`);
  if (index.next < 0) problems.push(`missing the heading "${HEADINGS.next}"`);
  if (index.build < 0 && index.tryit < 0) problems.push('needs a "Build it" section (code to run) or, for a concept lesson, a "Try it yourself" section');
  const order = [index.situation, index.concept, index.build >= 0 ? index.build : index.tryit, index.next];
  if (order.every((value) => value >= 0) && order.some((value, position) => position > 0 && value < order[position - 1]!)) problems.push('the headings must run: A real situation, How it works, Build it (or Try it yourself), Run it and check, Next steps');
  if (!body.some((block) => block.type === 'diagram' || block.type === 'visual' || block.type === 'table')) problems.push('needs a diagram, a visual or a table');
  if (index.next >= 0 && !body.slice(index.next).some((block) => block.type === 'list')) problems.push('"Next steps" needs a list');

  if (index.build >= 0) {
    const end = index.check >= 0 ? index.check : index.next >= 0 ? index.next : body.length;
    const built = body.slice(index.build, end);
    if (!built.some((block) => block.type === 'code' && RUNNABLE.test(block.language))) problems.push('"Build it" needs a complete code block (python, typescript, javascript, bash or sql)');
    if (index.check < 0) problems.push('a lesson with "Build it" needs a "Run it and check" section');
    else {
      const checked = body.slice(index.check, index.next >= 0 ? index.next : undefined);
      if (!checked.some((block) => block.type === 'code' && /^expected output/i.test(block.label ?? ''))) problems.push('"Run it and check" needs a code block whose label starts "Expected output"');
      if (!checked.some((block) => block.type === 'list')) problems.push('"Run it and check" needs a troubleshooting list ("If it fails: …")');
      if (!checked.some((block) => block.type === 'warning')) problems.push('"Run it and check" needs a warning block with the security consideration');
    }
  } else if (index.tryit >= 0) {
    const end = index.next >= 0 ? index.next : body.length;
    if (!body.slice(index.tryit, end).some((block) => block.type === 'prompt' || block.type === 'code' || block.type === 'list')) problems.push('"Try it yourself" needs something to do (a prompt, code or a list of steps)');
  }
  if (body.some((block) => block.type === 'code' && /(sk-[A-Za-z0-9]{16,}|sk-ant-[A-Za-z0-9_-]{8,}|AIza[0-9A-Za-z_-]{20,})/.test(block.code))) problems.push('a code block contains something that looks like a real API key: use a placeholder');
  if (kinds.size < 2) problems.push(`needs at least two activities of different kinds, has ${kinds.size} kind(s)`);
  if (!body.some((block) => block.audience && block.audience.max && !block.audience.min)) problems.push('needs a plain-language block for newcomers (audience { max: "beginner" })');
  if (!body.some((block) => block.audience && block.audience.min && !block.audience.max)) problems.push('needs a depth block for experienced learners (audience { min: "advanced" })');
  if ((lesson.taskExtra ?? []).length === 0) problems.push('needs taskExtra for at least one level');
  return problems;
}

/** Counts the module's "Build it" lessons and runnable coding exercises, for the per-module minimums. */
export function buildCounts(lessons: Lesson[]): { build: number; coding: number } {
  let build = 0;
  let coding = 0;
  for (const lesson of lessons) {
    if (headingAt(lesson.body, HEADINGS.build) >= 0) build += 1;
    coding += lesson.body.filter((block) => block.type === 'activity' && CODE_ACTIVITIES.has(block.activity.kind)).length;
  }
  return { build, coding };
}

const number = process.env.CHECK_AGENTS_MODULE;
const run = number ? describe : describe.skip;

run(`${COURSE} module ${number ?? '(none named)'}`, () => {
  test('follows every lesson rule and has the lesson parts', () => {
    const syllabus = getSyllabus(COURSE)!;
    const index = Number(number) - 1;
    const first = (syllabus.modules ?? []).slice(0, index).reduce((sum, module) => sum + module.topics.length, 0);
    const count = syllabus.modules?.[index]?.topics.length ?? 0;
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const loaded = require(`./courses/${COURSE}/module-${String(number).padStart(2, '0')}`) as { lessons: Lesson[]; project: Project | null };
    expect(loaded.lessons).toHaveLength(count);
    expect(loaded.lessons.map((lesson) => lesson.id)).toEqual(loaded.lessons.map((_, i) => `${COURSE}-${String(first + i + 1).padStart(2, '0')}`));
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const skills = (require(`./courses/${COURSE}/skills`) as { SKILLS: Course['skills'] }).SKILLS;
    const stub = (position: number): Lesson => ({
      id: `${COURSE}-${String(position + 1).padStart(2, '0')}`,
      day: position + 1,
      title: syllabus.topics[position]!,
      summary: 'stub',
      minutes: 10,
      skills: [],
      body: [],
      quiz: [],
      task: { title: 'stub', steps: [], minutes: 5 },
    });
    const lessons = syllabus.topics.map((_, position) => (position >= first && position < first + count ? loaded.lessons[position - first]! : stub(position)));
    const ordinal = loaded.project ? Number(/-p(\d+)$/.exec(loaded.project.id)?.[1] ?? 0) : 0;
    const projects: Project[] = loaded.project
      ? Array.from({ length: ordinal }, (_, position) => (position === ordinal - 1 ? loaded.project! : { id: `${COURSE}-p${position + 1}`, title: 'stub', summary: 'stub', outcome: 'stub', unlockAfterDay: 1, steps: [], submission: { kind: 'text', label: 'x', placeholder: 'x', hint: 'x' }, rubric: [] }))
      : [];
    const course: Course = {
      id: COURSE,
      kind: 'standard',
      title: syllabus.title,
      level: 'intermediate',
      tagline: 'A tagline that is long enough to pass',
      description: 'A description long enough to pass the length check of the course rules for the course page.',
      finishLine: ['one', 'two'],
      objectives: ['Explain what an agent is', 'Compare two solutions', 'Choose a tool'],
      audiences: ['experienced-dev'],
      skills,
      lessons,
      projects,
      icon: 'code',
      updated: '2026-11-18',
    };
    const mine = new Set([...loaded.lessons.map((lesson) => lesson.id), ...(loaded.project ? [loaded.project.id] : [])]);
    // An id must end where the problem names it: lesson 10 is a substring of the stubs 100 to 109.
    const names = (problem: string, id: string) => new RegExp(`${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?!\\d)`).test(problem);
    const problems = standardCourseProblems(course).filter((problem) => [...mine].some((id) => names(problem, id)) || /quiz answers|longest choice/.test(problem));
    const shape = loaded.lessons.flatMap((lesson) => shapeProblems(lesson, lesson.day).map((problem) => `${lesson.id}: ${problem}`));
    const counts = buildCounts(loaded.lessons);
    const minBuild = Number(process.env.CHECK_AGENTS_MIN_BUILD ?? 0);
    const minCoding = Number(process.env.CHECK_AGENTS_MIN_CODE ?? 0);
    const floors: string[] = [];
    if (counts.build < minBuild) floors.push(`the module needs at least ${minBuild} "Build it" lessons, has ${counts.build}`);
    if (counts.coding < minCoding) floors.push(`the module needs at least ${minCoding} runnable coding exercises (code-challenge, fix-bug or predict-output), has ${counts.coding}`);
    expect([...problems, ...shape, ...floors]).toEqual([]);
  });
});
